"""Evaluate caption similarity between human descriptions and generated captions.

This script compares human-written descriptions (from dataset CSV) with captions
generated by caption_generator and llm_classifier using multiple metrics:
- BLEU (1-4 grams)
- METEOR
- ROUGE-L
- BERTScore (using Portuguese BERT model)
"""
import argparse
import json
import sys
import pandas as pd
from pathlib import Path
from typing import Dict

project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from src.core.evaluation.caption_metrics import (
    evaluate_caption_pairs,
    print_metrics_summary
)


def load_human_descriptions(csv_path: str) -> Dict[str, str]:
    """Load human descriptions from dataset CSV.

    Args:
        csv_path: Path to dataset_completo.csv

    Returns:
        Dictionary mapping image filename to human description
    """
    df = pd.read_csv(csv_path)
    descriptions = {}

    for _, row in df.iterrows():
        filename = row['Item']
        description = row['Descrição (informal)']

        # Skip if no description
        if pd.isna(description) or description.strip() == '':
            continue

        descriptions[filename] = description.strip()

    return descriptions


def load_generated_captions(json_path: str) -> Dict[str, str]:
    """Load generated captions from JSON file.

    Expected JSON format:
    {
        "image1.jpg": "caption text",
        "image2.jpg": "caption text",
        ...
    }
    or
    [
        {"filename": "image1.jpg", "caption": "caption text"},
        {"filename": "image2.jpg", "caption": "caption text"},
        ...
    ]

    Args:
        json_path: Path to JSON file with generated captions

    Returns:
        Dictionary mapping image filename to generated caption
    """
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Handle dict format
    if isinstance(data, dict):
        return data

    # Handle list format
    if isinstance(data, list):
        captions = {}
        for item in data:
            if 'filename' in item and 'caption' in item:
                captions[item['filename']] = item['caption']
            elif 'Item' in item and 'caption' in item:
                captions[item['Item']] = item['caption']
        return captions

    raise ValueError(f"Unsupported JSON format in {json_path}")


def evaluate_captions(human_desc: Dict[str, str],
                      generated_captions: Dict[str, str],
                      caption_type: str,
                      bert_model: str) -> Dict:
    """Evaluate generated captions against human descriptions.

    Args:
        human_desc: Dictionary of human descriptions
        generated_captions: Dictionary of generated captions
        caption_type: Type of captions ('caption_generator' or 'llm_classifier')
        bert_model: BERT model for BERTScore

    Returns:
        Dictionary with aggregated metrics and caption_type
    """
    # Collect matching pairs
    references = []
    hypotheses = []
    filenames = []

    for filename, human_text in human_desc.items():
        if filename in generated_captions:
            references.append(human_text)
            hypotheses.append(generated_captions[filename])
            filenames.append(filename)

    if not references:
        print(f"Warning: No matching pairs found for {caption_type}")
        return {'caption_type': caption_type, 'num_pairs': 0, 'metrics': {}, 'per_image': []}

    # Evaluate using caption_metrics module
    results = evaluate_caption_pairs(
        references=references,
        hypotheses=hypotheses,
        filenames=filenames,
        bert_model=bert_model,
        verbose=True
    )

    # Add caption type
    results['caption_type'] = caption_type

    return results


def main():
    parser = argparse.ArgumentParser(description='Evaluate caption similarity metrics')
    parser.add_argument('--csv', type=str, required=True,
                        help='Path to dataset_completo.csv')
    parser.add_argument('--caption-generator', type=str,
                        help='Path to JSON file with caption_generator outputs')
    parser.add_argument('--llm-classifier', type=str,
                        help='Path to JSON file with llm_classifier outputs')
    parser.add_argument('--output', type=str, default='caption_evaluation_results.json',
                        help='Path to save evaluation results (JSON)')
    parser.add_argument('--bert-model', type=str,
                        default='neuralmind/bert-base-portuguese-cased',
                        help='BERT model for BERTScore (default: Portuguese BERT)')

    args = parser.parse_args()

    # Load human descriptions
    print(f"Loading human descriptions from {args.csv}...")
    human_desc = load_human_descriptions(args.csv)
    print(f"Loaded {len(human_desc)} human descriptions")

    all_results = []

    # Evaluate caption_generator
    if args.caption_generator:
        print(f"\nLoading caption_generator outputs from {args.caption_generator}...")
        try:
            caption_gen_captions = load_generated_captions(args.caption_generator)
            print(f"Loaded {len(caption_gen_captions)} generated captions")

            results = evaluate_captions(human_desc, caption_gen_captions, 'caption_generator', args.bert_model)
            all_results.append(results)
            print_metrics_summary(results, results['caption_type'])
        except Exception as e:
            print(f"Error processing caption_generator: {e}")

    # Evaluate llm_classifier
    if args.llm_classifier:
        print(f"\nLoading llm_classifier outputs from {args.llm_classifier}...")
        try:
            llm_captions = load_generated_captions(args.llm_classifier)
            print(f"Loaded {len(llm_captions)} generated captions")

            results = evaluate_captions(human_desc, llm_captions, 'llm_classifier', args.bert_model)
            all_results.append(results)
            print_metrics_summary(results, results['caption_type'])
        except Exception as e:
            print(f"Error processing llm_classifier: {e}")

    # Save results to JSON
    if all_results:
        print(f"\nSaving results to {args.output}...")
        with open(args.output, 'w', encoding='utf-8') as f:
            json.dump(all_results, f, indent=2, ensure_ascii=False)
        print("Done!")
    else:
        print("\nNo results to save. Please provide at least one caption file.")


if __name__ == '__main__':
    main()
